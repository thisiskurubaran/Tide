// Builds each WebView bundle in web/<name> with Vite and writes the single-file
// HTML into src/features/<name>/<name>Html.generated.ts, so the app needs no
// asset loading or network to show it.
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const bundles = fs
  .readdirSync(path.join(root, 'web'), { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join(root, 'web', d.name, 'vite.config.mjs')))
  .map((d) => d.name);

for (const name of bundles) {
  const dir = path.join(root, 'web', name);
  execFileSync(path.join(root, 'node_modules', '.bin', 'vite'), ['build', '--config', path.join(dir, 'vite.config.mjs')], {
    cwd: root,
    stdio: 'inherit',
  });
  const html = fs.readFileSync(path.join(dir, 'dist', 'index.html'), 'utf8');
  const out = path.join(root, 'src', 'features', name, `${name}Html.generated.ts`);
  fs.writeFileSync(
    out,
    `// Generated by npm run build:web from web/${name}. Do not edit.\nexport default ${JSON.stringify(html)};\n`,
  );
  console.log(`wrote ${path.relative(root, out)} (${(html.length / 1024).toFixed(0)} KB)`);
}
